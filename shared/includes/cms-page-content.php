    function cmsRenderBlogDetailContent(array $blog, array $options = []): void
    {
        $skipMainTitleH1 = !empty($options['skip_main_title_h1']);
        $categories = is_array($blog['categories'] ?? null) ? $blog['categories'] : [];
        if ($categories !== []) {
            $names = [];
            foreach ($categories as $cat) {
                if (!is_array($cat)) {
                    continue;
                }
                $name = trim((string) ($cat['name'] ?? ''));
                if ($name !== '') {
                    $names[] = '<strong>' . htmlspecialchars($name, ENT_QUOTES, 'UTF-8') . '</strong>';
                }
            }
            if ($names !== []) {
                echo '<div class="text-[#172B4D] text-[15px] tracking-[2px] mb-2">CATEGORY: ' . implode(', ', $names) . '</div>';
            }
        }

        $dateRaw = trim((string) ($blog['date'] ?? ''));
        if ($dateRaw === '' || $dateRaw === '0002-02-02') {
            $dateRaw = trim((string) ($blog['created_at'] ?? $blog['published_at'] ?? ''));
        }
        if ($dateRaw !== '' && $dateRaw !== '0002-02-02') {
            $timestamp = strtotime($dateRaw);
            if ($timestamp !== false) {
                echo '<div class="text-[#172B4D] text-[15px] mb-1">Published on <strong>'
                    . htmlspecialchars(date('d F Y', $timestamp), ENT_QUOTES, 'UTF-8') . '</strong></div>';
            }
        }

        $tags = is_array($blog['tag'] ?? null) ? $blog['tag'] : [];
        if ($tags === [] && is_array($blog['tags'] ?? null)) {
            $tags = $blog['tags'];
        }
        if ($tags !== []) {
            $tagNames = [];
            foreach ($tags as $tag) {
                if (!is_array($tag)) {
                    continue;
                }
                $name = trim((string) ($tag['name'] ?? ''));
                if ($name !== '') {
                    $tagNames[] = '<strong>' . htmlspecialchars($name, ENT_QUOTES, 'UTF-8') . '</strong>';
                }
            }
            if ($tagNames !== []) {
                echo '<div class="text-[#172B4D] text-[15px] mb-4">Tags: ' . implode(', ', $tagNames) . '</div>';
            }
        }

        $detailForTitle = null;
        foreach ($blog['blogdetails'] ?? [] as $row) {
            if (is_array($row)) {
                $detailForTitle = $row;
                break;
            }
        }
        $fallbackTitle = function_exists('cmsBlogPostTitle')
            ? cmsBlogPostTitle($blog, $detailForTitle)
            : trim((string) ($blog['main_title'] ?? $blog['title'] ?? ''));
        if ($fallbackTitle === 'Blog') {
            $fallbackTitle = '';
        }

        $displayTitle = trim((string) ($blog['meta_title'] ?? ''));
        if ($displayTitle === '') {
            $displayTitle = trim((string) ($blog['main_title'] ?? ''));
        }
        if ($displayTitle === '') {
            $displayTitle = $fallbackTitle;
        }

        $mainTitle = $displayTitle;

        /* if ($displayTitle !== '' && !$skipMainTitleH1) {
            echo '<h1 class="text-[#2B3C6B] text-[28px] sm:text-[40px] font-bold leading-tight mb-4">'
                . htmlspecialchars($displayTitle, ENT_QUOTES, 'UTF-8') . '</h1>';
        }

        $displayDescription = trim((string) ($blog['meta_description'] ?? ''));
        if ($displayDescription === '') {
            $displayDescription = trim((string) ($blog['main_description'] ?? ''));
        }

        $mainHasInlineMedia = $displayDescription !== '' && preg_match('/<img\b/i', $displayDescription) === 1;
        if ($displayDescription !== '' && ($mainHasInlineMedia || !cmsBlogTitlesEquivalent($displayDescription, $displayTitle))) {
            $mainDescriptionHtml = function_exists('cmsBlogDetailPrepareContent')
                ? cmsBlogDetailPrepareContent($displayDescription, $displayTitle)
                : (function_exists('cmsPrepareCmsHtml') ? cmsPrepareCmsHtml($displayDescription) : htmlspecialchars($displayDescription, ENT_QUOTES, 'UTF-8'));
            echo '<div class="text-[#70747F] text-[18px] sm:text-[20px] mb-10">' . $mainDescriptionHtml . '</div>';
        } */

        $details = is_array($blog['blogdetails'] ?? null) ? $blog['blogdetails'] : [];
        $seenSectionTitles = [];
        $isFirstImage = true;
        foreach ($details as $detail) {
            if (!is_array($detail)) {
                continue;
            }

            echo '<div class="mb-12">';

            $imageUrl = cmsBlogDetailSectionImageUrl($blog, $detail);
            $sectionTitle = trim((string) ($detail['title'] ?? ''));
            if (cmsBlogShouldRenderSectionTitle($sectionTitle, $mainTitle, $seenSectionTitles)) {
                echo '<h2 class="text-[#2B3C6B] text-[24px] sm:text-[32px] md:leading-10 mt-3 font-semibold">'
                    . htmlspecialchars($sectionTitle, ENT_QUOTES, 'UTF-8') . '</h2>';
            }

            if ($imageUrl !== '') {
                $altFallback = $sectionTitle !== '' ? $sectionTitle : $mainTitle;
                $alt = function_exists('cms_image_alt')
                    ? cms_image_alt($detail, $altFallback)
                    : htmlspecialchars($altFallback, ENT_QUOTES, 'UTF-8');
                $loading = $isFirstImage ? 'eager' : 'lazy';
                $fetchPriority = $isFirstImage ? ' fetchpriority="high"' : '';
                $isFirstImage = false;
                echo '<img src="' . htmlspecialchars($imageUrl, ENT_QUOTES, 'UTF-8') . '"'
                    . ' alt="' . $alt . '"'
                    . ' class="w-full mb-4 rounded-[10px]" loading="' . $loading . '"' . $fetchPriority . ' />';
            }

            $body = trim((string) ($detail['description'] ?? $detail['content'] ?? ''));
            if ($body !== '') {
                $bodyHtml = function_exists('cmsBlogDetailPrepareContent')
                    ? cmsBlogDetailPrepareContent($body, $mainTitle)
                    : (function_exists('cmsPrepareCmsHtml') ? cmsPrepareCmsHtml($body) : $body);
                echo '<div class="w-full sm:w-[90%] text-[#70747F] text-[18px] sm:text-[20px] mt-2">';
                echo '<div class="ql-snow"><div class="ql-editor">' . $bodyHtml . '</div></div>';
                echo '</div>';
            }

            echo '</div>';
        }

        if ($details === []) {
            $fallbackBody = trim((string) ($blog['content'] ?? $blog['description'] ?? ''));
            if ($fallbackBody !== '') {
                $bodyHtml = function_exists('cmsBlogDetailPrepareContent')
                    ? cmsBlogDetailPrepareContent($fallbackBody, $mainTitle)
                    : (function_exists('cmsPrepareCmsHtml') ? cmsPrepareCmsHtml($fallbackBody) : $fallbackBody);
                echo '<div class="text-[#70747F] text-[18px] sm:text-[20px] mt-2">';
                echo '<div class="ql-snow"><div class="ql-editor">' . $bodyHtml . '</div></div>';
                echo '</div>';
            }
        }
    }
}

if (!function_exists('cmsBlogDetailBodyHtml')) {
    /**
     * Merge all CMS blog detail sections (blogdetails[]) into one HTML body.
     *
     * @param array<string, mixed> $blog
     */
    function cmsBlogDetailBodyHtml(array $blog): string
    {
        $details = $blog['blogdetails'] ?? [];
        if (!is_array($details) || $details === []) {
            return (string) ($blog['content'] ?? $blog['description'] ?? $blog['main_description'] ?? '');
        }

        $sections = [];
        $index = 0;
        foreach ($details as $row) {
            if (!is_array($row)) {
                continue;
            }
            $body = trim((string) ($row['description'] ?? $row['content'] ?? ''));
            if ($body === '') {
                continue;
            }
            $sectionTitle = trim((string) ($row['title'] ?? ''));
            if ($index > 0 && $sectionTitle !== '') {
                $sections[] = '<h2 class="text-[28px] font-bold text-blue-main mt-10 mb-4">'
                    . htmlspecialchars($sectionTitle, ENT_QUOTES, 'UTF-8') . '</h2>' . $body;
            } else {
                $sections[] = $body;
            }
            $index++;
        }

        if ($sections !== []) {
            return implode("\n", $sections);
        }

        return (string) ($blog['content'] ?? $blog['description'] ?? $blog['main_description'] ?? '');
    }
}

if (!function_exists('cmsFindBlogBySlug')) {
    /** @return array<string, mixed>|null */
    function cmsFindBlogBySlug(string $blogSlug): ?array
    {
        $blogSlug = trim($blogSlug);
        if ($blogSlug === '') {
            return null;
        }
        $allBlogs = cmsBlogPostsListResolved();
        foreach ($allBlogs as $blog) {
            if (cmsBlogPostSlug($blog) === $blogSlug) {
                return $blog;
            }
        }

        if (function_exists('cmsFetchBlogBySlug')) {
            return cmsFetchBlogBySlug($blogSlug);
        }

        return null;
    }
