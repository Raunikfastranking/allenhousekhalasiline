if (!function_exists('cmsApplyPageTitleFallback')) {
    function cmsApplyPageTitleFallback(?array $page, string $fallback): array
    {
        if (!is_array($page) || !is_array($page['data'] ?? null)) {
            return is_array($page) ? $page : ['data' => []];
        }
        if ($fallback === '') {
            return $page;
        }

        $slug = trim((string) ($page['data']['slug'] ?? ($GLOBALS['cms_page_slug'] ?? '')));
        $pageHeading = trim((string) ($page['data']['page_heading'] ?? ''));
        $headingNeedsFallback = $pageHeading === ''
            || (function_exists('cmsPageTitleLooksAutoGenerated') && cmsPageTitleLooksAutoGenerated($pageHeading, $slug));
        if ($headingNeedsFallback) {
            $page['data']['page_heading'] = $fallback;
        }

        $currentTitle = trim((string) ($page['data']['title'] ?? ''));
        $titleNeedsFallback = $currentTitle === ''
            || (function_exists('cmsPageTitleLooksAutoGenerated') && cmsPageTitleLooksAutoGenerated($currentTitle, $slug));
        if ($titleNeedsFallback) {
            $page['data']['title'] = $fallback;
        }

        return $page;
    }
}

