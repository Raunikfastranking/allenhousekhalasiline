if (!function_exists('cmsFindNavBreadcrumbAncestors')) {
    /**
     * @param list<array<string, mixed>> $items
     * @param list<array{label: string, url: string}> $ancestors
     * @return list<array{label: string, url: string}>|null
     */
    function cmsFindNavBreadcrumbAncestors(array $items, string $targetKey, array $ancestors = []): ?array
    {
        foreach ($items as $item) {
            if (!is_array($item)) {
                continue;
            }

            $name = trim((string) ($item['name'] ?? ''));
            if ($name === '') {
                continue;
            }

            $rawUrl = trim((string) ($item['url'] ?? ''));
            $itemKey = cmsBreadcrumbPathKey($rawUrl);
            $children = is_array($item['children'] ?? null) ? $item['children'] : [];
            $parentCrumb = [
                'label' => $name,
                'url' => cmsBreadcrumbItemUrl($rawUrl, $name, $children !== []),
            ];

            if ($children !== []) {
                $found = cmsFindNavBreadcrumbAncestors(
                    $children,
                    $targetKey,
                    array_merge($ancestors, [$parentCrumb])
                );
                if ($found !== null) {
                    return $found;
                }
            }

            if ($itemKey !== '' && $itemKey === $targetKey) {
                return $ancestors;
            }
        }

        return null;
    }
}

if (!function_exists('cmsResolveBreadcrumbsFromNav')) {
    /**
     * @param array<string, mixed> $options
     * @return list<array{label: string, url: string}>
     */
    function cmsResolveBreadcrumbsFromNav(?array $page, array $options = []): array
    {
        if (!function_exists('cmsNavItems')) {
            return [];
        }

        $targetKeys = cmsBreadcrumbTargetKeys();
        if ($targetKeys === []) {
            return [];
        }

        $ancestors = null;
        foreach ($targetKeys as $targetKey) {
            $ancestors = cmsFindNavBreadcrumbAncestors(cmsNavItems(), $targetKey);
            if ($ancestors !== null) {
                break;
            }
        }

        if ($ancestors === null) {
            foreach ($targetKeys as $targetKey) {
                $static = cmsBreadcrumbStaticParentTrail($targetKey);
                if ($static !== []) {
                    $ancestors = $static;
                    break;
                }
            }
        }

        if ($ancestors === null) {
            return [];
        }

        $currentLabel = cmsPageBreadcrumbFallbackTitle($page, $options);
        if ($currentLabel === '') {
            return $ancestors;
        }

        $trail = $ancestors;
        $last = end($trail);
        if (
            is_array($last)
            && strtolower(trim((string) ($last['label'] ?? ''))) === strtolower(trim($currentLabel))
        ) {
            $last['url'] = '';
            $trail[key($trail)] = $last;
            return $trail;
        }

        $trail[] = [
            'label' => $currentLabel,
            'url' => '',
        ];

        return $trail;
    }
}

if (!function_exists('cmsResolveDetailPageBreadcrumbs')) {
    /**
     * Listing/detail pages: nav parents + listing page + current item.
     *
     * @param array<string, mixed> $options
     * @return list<array{label: string, url: string}>
     */
    function cmsResolveDetailPageBreadcrumbs(
        ?array $page,
        string $listingLabel,
        string $listingUrl,
        string $detailLabel,
        array $options = []
    ): array {
        $listingKey = cmsBreadcrumbPathKey($listingUrl);
        if ($listingKey === '') {
            $listingKey = cmsCurrentBreadcrumbPathKey();
        }

        $ancestors = null;
        if ($listingKey !== '' && function_exists('cmsNavItems')) {
            $ancestors = cmsFindNavBreadcrumbAncestors(cmsNavItems(), $listingKey);
        }
        if ($ancestors === null && $listingKey !== '') {
            $ancestors = cmsBreadcrumbStaticParentTrail($listingKey);
        }
        if ($ancestors === null) {
            $ancestors = [];
        }

        $trail = $ancestors;
        if ($listingLabel !== '') {
            $trail[] = [
                'label' => $listingLabel,
                'url' => $listingUrl,
            ];
        }
        if ($detailLabel !== '') {
            $trail[] = [
                'label' => $detailLabel,
                'url' => '',
            ];
        }

        if ($trail === [] && function_exists('cmsResolvePageBreadcrumbs')) {
            return cmsResolvePageBreadcrumbs($page, array_merge($options, [
            ]));
        }

        return $trail;
    }
}

if (!function_exists('cmsResolvePageBreadcrumbs')) {
    /**
     * CMS breadcrumbs when present; otherwise nav parents + page title (or fallback_crumbs).
     *
     * @param array<string, mixed> $options fallback_title, fallback_crumbs
     * @return list<array{label: string, url: string}>
     */
    function cmsResolvePageBreadcrumbs(?array $page, array $options = []): array
    {
        $data = is_array($page['data'] ?? null) ? $page['data'] : [];
        $fromApi = cmsNormalizeBreadcrumbItems(is_array($data['breadcrumbs'] ?? null) ? $data['breadcrumbs'] : []);
        if ($fromApi !== []) {
            return $fromApi;
        }

        $fallback = cmsNormalizeBreadcrumbItems(is_array($options['fallback_crumbs'] ?? null) ? $options['fallback_crumbs'] : []);
        if ($fallback !== []) {
            return $fallback;
        }

        $fromNav = cmsResolveBreadcrumbsFromNav($page, $options);
        if ($fromNav !== []) {
            return $fromNav;
        }

        return [
            [
                'label' => cmsPageBreadcrumbFallbackTitle($page, $options),
                'url' => '',
            ],
        ];
    }
}

if (!function_exists('cmsRenderBreadcrumbsNav')) {
    /**
     * @param list<array{label: string, url: string}> $items
     */
    function cmsRenderBreadcrumbsNav(array $items, string $navClass = 'cms-page-breadcrumbs w-full flex m-5'): void
    {
        if ($items === []) {
            return;
        }

        $deduped = [];
        $lastLabelKey = null;
        foreach ($items as $item) {
            $labelKey = strtolower(trim((string) ($item['label'] ?? '')));
            if (in_array($labelKey, ['blog', 'blogs'], true)) {
                $labelKey = 'blog';
            }
            if ($labelKey === '' || $labelKey === $lastLabelKey) {
                continue;
            }
            $deduped[] = $item;
            $lastLabelKey = $labelKey;
        }
        $items = $deduped;
        if ($items === []) {
            return;
        }

        $homeUrl = function_exists('site_page_url') ? site_page_url('/') : '/';
        echo '<nav class="' . htmlspecialchars($navClass, ENT_QUOTES, 'UTF-8') . '" aria-label="Breadcrumb">';
        echo '<ol class="inline-flex items-center flex-wrap gap-1 md:space-x-2">';
        echo '<li><a href="' . htmlspecialchars($homeUrl, ENT_QUOTES, 'UTF-8') . '" class="text-xs sm:text-sm font-medium text-blue-main hover:underline">Home</a></li>';

        foreach ($items as $item) {
            $label = htmlspecialchars($item['label'], ENT_QUOTES, 'UTF-8');
            $url = trim((string) ($item['url'] ?? ''));
            echo '<li class="flex items-center">';
            echo '<svg class="w-3 h-3 text-blue-main mx-1" fill="none" viewBox="0 0 6 10" aria-hidden="true"><path stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="m1 9 4-4-4-4"/></svg>';
            if ($url !== '') {
                echo '<a href="' . htmlspecialchars($url, ENT_QUOTES, 'UTF-8') . '" class="text-xs sm:text-sm font-medium text-blue-main hover:underline">' . $label . '</a>';
            } else {
                echo '<span class="text-xs sm:text-sm font-medium text-gray-500">' . $label . '</span>';
            }
            echo '</li>';
        }

        echo '</ol></nav>';
    }
}

