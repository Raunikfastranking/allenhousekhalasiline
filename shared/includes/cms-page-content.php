if (!function_exists('cmsBlogPostsList')) {
    /** @return list<array<string, mixed>> */
    function cmsBlogPostsList(?array $rawBlogData = null): array
    {
        $raw = $rawBlogData ?? $GLOBALS['api_cache']['blogData'] ?? $GLOBALS['api_cache']['blog_data'] ?? [];
        if (!is_array($raw)) {
            return [];
        }
        if (isset($raw['data']['data']) && is_array($raw['data']['data'])) {
            return array_values(array_filter($raw['data']['data'], 'is_array'));
        }
        if (isset($raw['data']) && is_array($raw['data'])) {
            $data = $raw['data'];
            if (isset($data[0]) || $data === []) {
                return array_values(array_filter($data, 'is_array'));
            }
        }

        return [];
    }
}

if (!function_exists('cmsBlogPostTitle')) {
    /** @param array<string, mixed> $blog */
    function cmsBlogPostTitle(array $blog, ?array $details = null): string
    {
        foreach (['title', 'main_title', 'post_title', 'heading'] as $key) {
            $value = trim((string) ($blog[$key] ?? ''));
            if ($value !== '') {
                return $value;
            }
        }
        if (is_array($details)) {
            $detailTitle = trim((string) ($details['title'] ?? ''));
            if ($detailTitle !== '') {
                return $detailTitle;
            }
        }

        return 'Blog';
    }
}

if (!function_exists('cmsBlogPostSlug')) {
    /** CMS URL slug only — never derived from title/heading (DPS: $blog['slug']). */
    function cmsBlogPostSlug(array $blog): string
    {
        foreach (['slug', 'blog_slug', 'post_slug', 'url_slug', 'permalink'] as $key) {
            $value = trim((string) ($blog[$key] ?? ''));
            if ($value !== '' && strtolower($value) !== 'null') {
                return $value;
            }
        }

        return '';
    }
}

if (!function_exists('cmsFetchBlogPostsForBranch')) {
    /** @return list<array<string, mixed>> */
    function cmsFetchBlogPostsForBranch(): array
    {
        if (!defined('CMS_API_URL') || !defined('BRANCH_ID')) {
            return [];
        }
        $url = rtrim((string) CMS_API_URL, '/') . '/blogs/branch/' . (int) BRANCH_ID;
        $decoded = null;
        if (function_exists('cms_curl_get_json')) {
            if (function_exists('cms_curl_json_cache_ref')) {
                $curlCache = &cms_curl_json_cache_ref();
                unset($curlCache[$url]);
            }
            $decoded = cms_curl_get_json($url);
        } else {
            $ctx = stream_context_create([
                'http' => ['timeout' => 20, 'header' => "Accept: application/json\r\n"],
                'ssl' => ['verify_peer' => true, 'verify_peer_name' => true],
            ]);
            $json = @file_get_contents($url, false, $ctx);
            if (is_string($json) && $json !== '') {
                $decoded = json_decode($json, true);
            }
        }
        if (!is_array($decoded)) {
            return [];
        }
        if (isset($GLOBALS['api_cache']) && is_array($GLOBALS['api_cache'])) {
            $GLOBALS['api_cache']['blogData'] = $decoded;
        }

        return cmsBlogPostsList($decoded);
    }
}

if (!function_exists('cmsBlogPostsListResolved')) {
    /** Use scoped bulk cache when available; live-fetch only when cache is empty. */
    function cmsBlogPostsListResolved(): array
    {
        $posts = cmsBlogPostsList();
        if ($posts === []) {
            $posts = cmsFetchBlogPostsForBranch();
        }
        if ($posts === [] || !function_exists('cmsNormalizeBlogItem')) {
            return $posts;
        }

        $items = [];
        foreach ($posts as $blog) {
            if (!is_array($blog)) {
                continue;
            }
            $normalized = cmsNormalizeBlogItem($blog);
            $slug = cmsBlogPostSlug($normalized);
            if ($slug !== '') {
                $normalized['slug'] = $slug;
            }
            $items[] = $normalized;
        }

        return $items;
