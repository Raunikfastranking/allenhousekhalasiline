if (!function_exists('cmsRenderInnerPageHeader')) {
    /**
     * Banner + breadcrumbs for standalone inner pages (forms, utilities).
     *
     * @param array<string, mixed> $options fallback_title, fallback_crumbs
     */
    function cmsRenderInnerPageHeader(?array $page, string $fallbackTitle = '', array $options = []): void
    {
        if ($fallbackTitle !== '') {
            $options['fallback_title'] = $fallbackTitle;
        }
        if (is_array($page)) {
            if (!isset($page['data']) || !is_array($page['data'])) {
                $page['data'] = [];
            }
            if ($fallbackTitle !== '' && trim((string) ($page['data']['page_heading'] ?? '')) === '') {
                $page['data']['page_heading'] = $fallbackTitle;
            }
            if ($fallbackTitle !== '' && trim((string) ($page['data']['title'] ?? '')) === '') {
                $page['data']['title'] = $fallbackTitle;
            }
        }
        if (function_exists('cmsRenderPageBanner')) {
            cmsRenderPageBanner($page, $options);
        }
        if (function_exists('cmsRenderPageBreadcrumbs')) {
            cmsRenderPageBreadcrumbs($page, $options);
        }
    }
}

if (!function_exists('cmsPageBreadcrumbFallbackTitle')) {
    function cmsPageBreadcrumbFallbackTitle(?array $page, array $options = []): string
    {
        if (function_exists('cmsPageBannerTitle')) {
            $title = cmsPageBannerTitle($page);
            if ($title !== '') {
                return $title;
            }
        }

        $title = cmsPageDisplayTitleSafe($page, '');
        if ($title !== '') {
            return $title;
        }

        if (!empty($options['fallback_title'])) {
            return trim((string) $options['fallback_title']);
        }

        if (!empty($GLOBALS['cms_page_title_fallback'])) {
            return trim((string) $GLOBALS['cms_page_title_fallback']);
        }

        $script = basename($_SERVER['SCRIPT_FILENAME'] ?? '', '.php');
        if ($script === '' || $script === 'index') {
            return 'Page';
        }

        return ucwords(str_replace(['-', '_'], ' ', $script));
    }
}

if (!function_exists('cmsNormalizeBreadcrumbItems')) {
    /**
     * @param list<mixed> $items
     * @return list<array{label: string, url: string}>
     */
    function cmsNormalizeBreadcrumbItems(array $items): array
    {
        $normalized = [];
        foreach ($items as $item) {
            if (!is_array($item)) {
                continue;
            }
            $label = trim((string) ($item['label'] ?? $item['title'] ?? ''));
            if ($label === '') {
                continue;
            }
            $normalized[] = [
                'label' => $label,
                'url' => trim((string) ($item['url'] ?? $item['href'] ?? '')),
            ];
        }

        return $normalized;
    }
}

if (!function_exists('cmsBreadcrumbPathKey')) {
    function cmsBreadcrumbPathKey(?string $urlOrPath): string
    {
        $value = trim((string) $urlOrPath);
        if ($value === '' || $value === '#') {
            return '';
        }

        if (preg_match('#^https?://#i', $value)) {
            $host = strtolower((string) parse_url($value, PHP_URL_HOST));
            $path = (string) (parse_url($value, PHP_URL_PATH) ?: '');
            $isInternal = $host === ''
                || $host === 'localhost'
                || $host === '127.0.0.1'
                || str_contains($host, 'allenhouse');
            if (!$isInternal) {
                return '';
            }
            $value = $path;
        }

        $value = trim($value, '/');
        if (function_exists('site_base_url')) {
            $base = trim(site_base_url(), '/');
            if ($base !== '' && str_starts_with($value, $base . '/')) {
                $value = trim(substr($value, strlen($base)), '/');
            } elseif ($base !== '' && $value === $base) {
                $value = '';
            }
        }

        $value = preg_replace('/\.php$/', '', $value);
        $value = strtolower(trim((string) preg_replace('#/+#', '/', $value), '/'));

        return $value === 'index' ? '' : $value;
    }
}

if (!function_exists('cmsCurrentBreadcrumbPathKey')) {
    function cmsCurrentBreadcrumbPathKey(): string
    {
        $keys = cmsBreadcrumbTargetKeys();

        return $keys[0] ?? '';
    }
}

if (!function_exists('cmsBreadcrumbTargetKeys')) {
    /** @return list<string> */
    function cmsBreadcrumbTargetKeys(): array
    {
        $keys = [];
        $script = basename($_SERVER['SCRIPT_FILENAME'] ?? '', '.php');

        if (function_exists('cms_current_page_map_key')) {
            $mapKey = trim((string) cms_current_page_map_key());
            if ($mapKey !== '' && $mapKey !== 'index') {
                if (str_contains($mapKey, '/')) {
                    $parts = explode('/', $mapKey);
                    $mapKey = end($parts) ?: $mapKey;
                }
                $keys[] = cmsBreadcrumbPathKey($mapKey);
            }
        }

        $keys[] = cmsBreadcrumbPathKey($script);

        if (function_exists('cmsBreadcrumbScriptPathAliases')) {
            $alias = cmsBreadcrumbScriptPathAliases()[$script] ?? '';
            if ($alias !== '') {
                $keys[] = cmsBreadcrumbPathKey($alias);
            }
        }

        if (function_exists('cmsRoomaSlugFromScript')) {
            $slug = cmsRoomaSlugFromScript($script);
            $slugPath = preg_replace('/-page-rooma$/', '', $slug);
            $keys[] = cmsBreadcrumbPathKey($slugPath);
        }

        $canonical = trim((string) ($GLOBALS['cms_canonical_path'] ?? ''));
        if ($canonical !== '') {
            $keys[] = cmsBreadcrumbPathKey($canonical);
        }

        return array_values(array_unique(array_filter($keys)));
    }
}

if (!function_exists('cmsBreadcrumbStaticParentTrail')) {
    /**
     * Parents for pages not nested in the header menu.
     *
     * @return list<array{label: string, url: string}>
     */
    function cmsBreadcrumbStaticParentTrail(string $targetKey): array
    {
        $map = [
            'careers' => [['label' => 'Careers', 'url' => cmsBreadcrumbHref('careers')]],
            'blog' => [['label' => 'Blog', 'url' => cmsBreadcrumbHref('blog')]],
        ];

        return $map[$targetKey] ?? [];
    }
}

if (!function_exists('cmsBreadcrumbParentPathFromLabel')) {
    function cmsBreadcrumbParentPathFromLabel(string $label): string
    {
        $normalized = strtolower(trim($label));
        $map = [
            'academics' => 'results-and-academics',
            'beyond academics' => 'extra-carricular',
            'media & events' => 'event',
            'mpd' => 'mandatory-public-disclosure',
            'board toppers' => 'x-toppers',
            'achievements' => 'achievements',
        ];
        if (isset($map[$normalized])) {
            return $map[$normalized];
        }

        $slug = preg_replace('/\s*&\s*/', ' ', $normalized);
        $slug = preg_replace('/[^a-z0-9]+/', '-', $slug);

        return trim((string) $slug, '-');
    }
}

if (!function_exists('cmsBreadcrumbHref')) {
    function cmsBreadcrumbHref(string $path): string
    {
        $path = trim($path, '/');
        if ($path === '') {
            return '';
        }

        if (function_exists('site_page_url')) {
            return site_page_url($path);
        }

        if (function_exists('site_base_url')) {
            return site_base_url() . $path;
        }

        return $path;
    }
}

