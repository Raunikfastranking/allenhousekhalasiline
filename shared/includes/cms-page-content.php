if (!function_exists('site_page_url')) {
    function site_page_url(string $path = ''): string
    {
        $path = trim($path, '/');
        $base = function_exists('site_base_url') ? site_base_url() : '/';
        if ($path === '') {
            return rtrim($base, '/') . '/';
        }

        return $base . $path;
    }
}
if (!function_exists('cmsSectionHasRenderableContent')) {
    function cmsSectionHasRenderableContent(array $section): bool
    {
        if (trim((string) ($section['content'] ?? '')) !== ''
            || trim((string) ($section['content_heading'] ?? '')) !== '') {
            return true;
        }

        $columns = $section['columns'] ?? [];
        if (is_array($columns)) {
            foreach ($columns as $column) {
                if (!is_array($column)) {
                    continue;
                }
                if (trim((string) ($column['content'] ?? '')) !== '') {
                    return true;
                }
                $image = trim((string) ($column['image_url'] ?? $column['image_path'] ?? ''));
                if ($image !== '') {
                    return true;
                }
            }
        }

        $items = $section['resolved_content']['items'] ?? [];
        if (is_array($items) && $items !== []) {
            return true;
        }

        $media = $section['resolved_content']['media'] ?? [];
        if (is_array($media) && $media !== []) {
            return true;
        }

        $gallery = $section['gallery_json_data'] ?? $section['resolved_content']['gallery_json_data'] ?? null;
        if (is_string($gallery) && trim($gallery) !== '' && trim($gallery) !== '[]') {
            return true;
        }

        $accordion = $section['accordion_json_data'] ?? $section['resolved_content']['accordion_json_data'] ?? null;
        if (is_string($accordion) && trim($accordion) !== '' && trim($accordion) !== '[]') {
            return true;
        }

        return false;
    }
}

if (!function_exists('cmsPageHasRenderableContent')) {
    function cmsPageHasRenderableContent(?array $page): bool
    {
        if (!is_array($page) || empty($page['data'])) {
            return false;
        }
        $sections = $page['data']['sections'] ?? [];
        if (!is_array($sections) || $sections === []) {
            if (trim((string) ($page['data']['content'] ?? '')) !== '') {
                return true;
            }
            if (function_exists('cmsPageIsPublished') && cmsPageIsPublished($page)) {
                return true;
            }

            return false;
        }
        foreach ($sections as $section) {
            if (!is_array($section)) {
                continue;
            }
            if (cmsSectionHasRenderableContent($section)) {
                return true;
            }
        }

        return false;
    }
}

if (!function_exists('cmsPageDisplayTitleSafe')) {
    function cmsPageDisplayTitleSafe(?array $page, string $fallback = ''): string
    {
        if (function_exists('cmsPageDisplayTitle')) {
            return cmsPageDisplayTitle($page, $fallback);
        }
        $data = is_array($page['data'] ?? null) ? $page['data'] : [];
        $title = trim((string) ($data['page_heading'] ?? $data['title'] ?? ''));

        return $title !== '' ? $title : $fallback;
    }
}

