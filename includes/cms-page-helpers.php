function cmsSectionTwoColumnHtml(?array $section): string
{
    if (!is_array($section)) {
        return '';
    }

    require_once __DIR__ . '/api-adapters.php';

    $imageUrl = '';
    $textHtml = '';
    foreach ($section['columns'] ?? [] as $col) {
        if (!is_array($col)) {
            continue;
        }
        if (($col['content_type'] ?? '') === 'image') {
            $imageUrl = cmsAssetUrl($col['image_url'] ?? $col['image_path'] ?? '');
        }
        if (($col['content_type'] ?? '') === 'text') {
            $textHtml = function_exists('cmsPrepareCmsHtml')
                ? cmsPrepareCmsHtml((string) ($col['content'] ?? ''))
                : (string) ($col['content'] ?? '');
        }
    }

    if ($textHtml === '') {
        $textHtml = cmsSectionBodyHtml($section);
    }

    if ($imageUrl === '' && $textHtml === '') {
        return '';
    }

    $textClass = $imageUrl !== '' ? 'sm:w-[60%]' : 'w-full';

    ob_start();
    echo '<div class="sm:flex gap-7">';
    if ($imageUrl !== '') {
        echo '<div class="sm:w-[40%]">';
        echo '<img src="' . htmlspecialchars($imageUrl, ENT_QUOTES, 'UTF-8') . '" alt="" class="w-[100%]">';
        echo '</div>';
    }
    echo '<div class="' . $textClass . ' sm:mt-0 mt-3">';
    echo $textHtml;
    echo '</div></div>';

    return (string) ob_get_clean();
}

