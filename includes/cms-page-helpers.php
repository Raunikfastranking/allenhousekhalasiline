if (!function_exists('cmsHumanTitleFromSlug')) {
    function cmsHumanTitleFromSlug(string $slug): string
    {
        $slug = trim(strtolower($slug));
        if ($slug === '') {
            return '';
        }

        $base = preg_replace('/-page-[a-z0-9-]+$/', '', $slug);
        $base = trim((string) $base, '-');

        return ucwords(str_replace(['-', '_'], ' ', $base));
    }
}

if (!function_exists('cmsPageTitleStripSectionPrefix')) {
    function cmsPageTitleStripSectionPrefix(string $title): string
    {
        $title = trim($title);
        if ($title === '') {
            return '';
        }

        if (preg_match('/^Admission\s*-\s*(.+)$/iu', $title, $matches)) {
            $segment = trim((string) ($matches[1] ?? ''));
            if ($segment !== '') {
                return ucwords(strtolower($segment));
            }
        }

        return $title;
    }
}

if (!function_exists('cmsPageTitleLooksAutoGenerated')) {
    function cmsPageTitleLooksAutoGenerated(string $title, string $slug = ''): bool
    {
        $title = trim($title);
        if ($title === '') {
            return false;
        }

        if (preg_match('/\bPage\s+Khalasiline\s*$/i', $title)) {
            return true;
        }

        if (preg_match('/\bKhalasiline\s*$/i', $title) && preg_match('/\bPage\b/i', $title)) {
            return true;
        }

        if ($slug !== '') {
            $fromSlug = cmsHumanTitleFromSlug($slug);
            if ($fromSlug !== '' && strcasecmp($title, $fromSlug . ' Page Khalasiline') === 0) {
                return true;
            }
        }

        return false;
    }
}

if (!function_exists('cmsKhalasilineScriptFallbackTitle')) {
    function cmsKhalasilineScriptFallbackTitle(string $slug): string
    {
        $mapFile = __DIR__ . '/cms-webpage-map.php';
        if (!is_file($mapFile)) {
            return '';
        }

        $map = require $mapFile;
        if (!is_array($map)) {
            return '';
        }

        foreach ($map as $script => $label) {
            if (cmsKhalasilineSlugFromScript((string) $script) === $slug) {
                return trim((string) $label);
            }
        }

        return '';
    }
}

if (!function_exists('cmsKhalasilineResolvePageTitle')) {
    function cmsKhalasilineResolvePageTitle(?array $page, string $slug = '', string $fallback = ''): string
    {
        if (!is_array($page)) {
            return $fallback !== '' ? $fallback : cmsHumanTitleFromSlug($slug);
        }

        $slug = trim($slug !== '' ? $slug : (string) ($page['data']['slug'] ?? ''));
        $fallback = trim($fallback);
        if ($fallback === '') {
            $fallback = trim((string) ($GLOBALS['cms_page_title_fallback'] ?? ''));
        }
        if ($fallback === '' && $slug !== '') {
            $fallback = cmsKhalasilineScriptFallbackTitle($slug);
        }
        if ($fallback === '' && $slug !== '') {
            $fallback = cmsHumanTitleFromSlug($slug);
        }

        $data = $page['data'] ?? [];
        foreach (['page_heading', 'title'] as $key) {
            $value = trim((string) ($data[$key] ?? ''));
            if (function_exists('cmsPrepareCmsPlainText')) {
                $value = trim(cmsPrepareCmsPlainText($value));
            }
            if ($value === '') {
                continue;
            }
            if (cmsPageTitleLooksAutoGenerated($value, $slug)) {
                $resolved = $fallback !== '' ? $fallback : $value;

                return cmsPageTitleStripSectionPrefix($resolved);
            }

            return cmsPageTitleStripSectionPrefix($value);
        }

        return cmsPageTitleStripSectionPrefix($fallback);
    }
}

if (!function_exists('cmsKhalasilineNormalizePageTitles')) {
    function cmsKhalasilineNormalizePageTitles(array $page, string $slug = '', string $fallback = ''): array
    {
        if (!isset($page['data']) || !is_array($page['data'])) {
            return $page;
        }

        $resolved = cmsKhalasilineResolvePageTitle($page, $slug, $fallback);
        if ($resolved === '') {
            return $page;
        }

        foreach (['page_heading', 'title'] as $key) {
            $value = trim((string) ($page['data'][$key] ?? ''));
            if ($value === '' || cmsPageTitleLooksAutoGenerated($value, $slug)) {
                $page['data'][$key] = $resolved;
            }
        }

        return $page;
    }
}

function cmsPageDisplayTitle(?array $page, string $fallback = ''): string
{
    $slug = trim((string) ($GLOBALS['cms_page_slug'] ?? ($page['data']['slug'] ?? '')));

    return cmsKhalasilineResolvePageTitle($page, $slug, $fallback);
}

