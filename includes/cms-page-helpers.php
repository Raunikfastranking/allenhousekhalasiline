/**
 * @return array{banner_html: string, table_html: string, content_html: string}
 */
function cmsExtractPageParts(array $raw_page): array
{
    $sections = is_array($raw_page['data']['sections'] ?? null) ? $raw_page['data']['sections'] : [];
    $banner_html = '';
    $table_html = '';
    $content_html = '';
    $usedIndices = [];

    foreach ($sections as $index => $section) {
        if (!is_array($section)) {
            continue;
        }
        $title = trim((string) ($section['title'] ?? ''));
        $body = trim((string) ($section['content'] ?? ''));
        if ($body === '') {
            $body = trim((string) ($section['content_heading'] ?? ''));
        }
        if ($body === '') {
            continue;
        }
        $bodyHtml = function_exists('cmsPrepareCmsHtml') ? cmsPrepareCmsHtml($body) : $body;

        if (stripos($title, 'hero') !== false || stripos($title, 'banner') !== false) {
            $banner_html = $bodyHtml;
            $usedIndices[] = (int) $index;
            continue;
        }
        if (stripos($title, 'table') !== false || stripos($body, '<table') !== false) {
            $table_html = $bodyHtml;
            $usedIndices[] = (int) $index;
            continue;
        }
        if ($content_html === '') {
            $content_html = $bodyHtml;
            $usedIndices[] = (int) $index;
        }
    }

    if ($table_html === '' && $content_html === '' && !empty($raw_page['data']['content'])) {
        $main = (string) $raw_page['data']['content'];
        if (stripos($main, '<table') !== false) {
            $table_html = function_exists('cmsPrepareCmsHtml') ? cmsPrepareCmsHtml($main) : $main;
        } else {
            $content_html = function_exists('cmsPrepareCmsHtml') ? cmsPrepareCmsHtml($main) : $main;
        }
    }

    if (function_exists('cmsMarkExtractPagePartsRendered')) {
        cmsMarkExtractPagePartsRendered($raw_page, $usedIndices);
    }

    return [
        'banner_html' => $banner_html,
        'table_html' => $table_html,
        'content_html' => $content_html,
    ];
}

