function cmsFetchBlogBySlug(string $slug): ?array
{
    $slug = trim($slug);
    if ($slug === '') {
        return null;
    }

    static $cache = [];
    if (array_key_exists($slug, $cache)) {
        return $cache[$slug];
    }

    if (!defined('CMS_API_URL')) {
        require_once dirname(__DIR__) . '/proxy/config.php';
    }

    $url = rtrim(CMS_API_URL, '/') . '/blogs/slug/' . rawurlencode($slug);
    $ch = curl_init($url);
    curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
    curl_setopt($ch, CURLOPT_CONNECTTIMEOUT, 5);
    curl_setopt($ch, CURLOPT_TIMEOUT, 20);
    curl_setopt($ch, CURLOPT_HTTPHEADER, function_exists('api_auth_headers') ? api_auth_headers() : []);
    curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, false);
    curl_setopt($ch, CURLOPT_SSL_VERIFYHOST, 0);
    $response = curl_exec($ch);
    $httpCode = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    if ($response === false || $httpCode !== 200) {
        $cache[$slug] = null;
        return null;
    }

    $decoded = json_decode((string) $response, true);
    if (!is_array($decoded)) {
        $cache[$slug] = null;
        return null;
    }

    $item = $decoded['data'] ?? null;
    if (!is_array($item)) {
        $cache[$slug] = null;
        return null;
    }

    require_once __DIR__ . '/api-adapters.php';
    $cache[$slug] = cmsNormalizeBlogItem($item);

    return $cache[$slug];
}

